/**
 * Email service.
 * -------------------------------------------------------------------------
 * Uses SMTP via Nodemailer if SMTP_HOST is configured. Otherwise it logs
 * the email to the console instead of sending it — so local development
 * and demos never fail just because email isn't configured yet.
 * -------------------------------------------------------------------------
 */
const nodemailer = require('nodemailer');

function getTransport() {
  if (!process.env.SMTP_HOST) return null;
  return nodemailer.createTransport({
    host: process.env.SMTP_HOST,
    port: Number(process.env.SMTP_PORT || 587),
    secure: process.env.SMTP_SECURE === 'true',
    auth: process.env.SMTP_USER ? { user: process.env.SMTP_USER, pass: process.env.SMTP_PASS } : undefined,
  });
}

async function send({ to, subject, text, html }) {
  const transport = getTransport();
  const from = process.env.MAIL_FROM || 'AXTEC Technologies <no-reply@axtec.tech>';

  if (!transport) {
    console.log('\n[email:DEV MODE — not actually sent] ---------------------------------');
    console.log('To:', to);
    console.log('Subject:', subject);
    console.log(text);
    console.log('----------------------------------------------------------------------\n');
    return { sent: false, mode: 'dev-log' };
  }

  await transport.sendMail({ from, to, subject, text, html });
  return { sent: true, mode: 'smtp' };
}

function clientConfirmationEmail(lead, lang) {
  const isEs = lang !== 'en';
  const subject = isEs ? 'Recibimos tu proyecto — AXTEC' : 'We received your project — AXTEC';
  const text = isEs
    ? `Hola ${lead.name},\n\nGracias por contactar a AXTEC.\n\nRecibimos la información de tu proyecto. Hemos preparado una estimación preliminar basada en las características que nos proporcionaste.\n\nNuestro equipo revisará el proyecto y se pondrá en contacto contigo para definir el alcance y la cotización final.\n\nSaludos,\nAXTEC Technologies`
    : `Hi ${lead.name},\n\nThanks for reaching out to AXTEC.\n\nWe received your project details. We've put together a preliminary estimate based on what you shared.\n\nOur team will review the project and reach out to define the final scope and quote.\n\nBest,\nAXTEC Technologies`;
  return { subject, text };
}

function internalNotificationEmail(lead, lang) {
  const isEs = lang !== 'en';
  const subject = isEs ? 'Nuevo Lead — AXTEC AI' : 'New Lead — AXTEC AI';
  const p = lead.project_data || {};
  const text = [
    isEs ? 'Nuevo lead generado por AXTEC AI' : 'New lead generated by AXTEC AI',
    '',
    `${isEs ? 'Nombre' : 'Name'}: ${lead.name}`,
    `${isEs ? 'Empresa' : 'Company'}: ${lead.company || '-'}`,
    `${isEs ? 'Correo' : 'Email'}: ${lead.email}`,
    `WhatsApp: ${lead.phone || '-'}`,
    `${isEs ? 'Servicio' : 'Service'}: ${p.project_type || '-'}`,
    `${isEs ? 'Estimación' : 'Estimate'}: ${lead.estimated_price_min ?? '-'} - ${lead.estimated_price_max ?? '-'} MXN`,
    `${isEs ? 'Tiempo' : 'Time'}: ${lead.estimated_days_min ?? '-'} - ${lead.estimated_days_max ?? '-'} ${isEs ? 'días' : 'days'}`,
    `${isEs ? 'Características' : 'Features'}: ${(p.features || []).join(', ') || '-'}`,
    '',
    `${isEs ? 'Resumen de conversación' : 'Conversation summary'}:`,
    lead.summary || '-',
  ].join('\n');
  return { subject, text };
}

module.exports = { send, clientConfirmationEmail, internalNotificationEmail };
